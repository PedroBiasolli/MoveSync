CREATE TABLE MS_USUARIO (
    ID          RAW(16)          NOT NULL,
    NOME        NVARCHAR2(120)   NOT NULL,
    EMAIL       NVARCHAR2(160)   NOT NULL,
    SENHA_HASH  NVARCHAR2(200)   NOT NULL,
    PERFIL      NVARCHAR2(30)    NOT NULL,   -- Cidadao | Gestor
    ATIVO       NUMBER(1)        NOT NULL,
    CRIADO_EM   TIMESTAMP(7)     NOT NULL,
    CONSTRAINT PK_MS_USUARIO PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX IX_MS_USUARIO_EMAIL ON MS_USUARIO (EMAIL);

CREATE TABLE MS_CRUZAMENTO (
    ID                        RAW(16)         NOT NULL,
    CODIGO                    NVARCHAR2(20)   NOT NULL,
    NOME                      NVARCHAR2(120)  NOT NULL,
    ENDERECO                  NVARCHAR2(200)  NOT NULL,
    LATITUDE                  BINARY_DOUBLE   NOT NULL,
    LONGITUDE                 BINARY_DOUBLE   NOT NULL,
    LARGURA_TRAVESSIA_METROS  BINARY_DOUBLE   NOT NULL,
    MODO                      NVARCHAR2(30)   NOT NULL,   -- Adaptativo | TempoFixo
    ATIVO                     NUMBER(1)       NOT NULL,
    CRIADO_EM                 TIMESTAMP(7)    NOT NULL,
    ATUALIZADO_EM             TIMESTAMP(7)    NOT NULL,
    CONSTRAINT PK_MS_CRUZAMENTO PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX IX_MS_CRUZAMENTO_CODIGO ON MS_CRUZAMENTO (CODIGO);

CREATE TABLE MS_VIA (
    ID                     RAW(16)         NOT NULL,
    CRUZAMENTO_ID          RAW(16)         NOT NULL,
    NOME                   NVARCHAR2(100)  NOT NULL,
    SENTIDO                NVARCHAR2(60)   NOT NULL,
    NUMERO_FAIXAS          NUMBER(10)      NOT NULL,
    VELOCIDADE_MAXIMA_KMH  NUMBER(10)      NOT NULL,
    ATIVA                  NUMBER(1)       NOT NULL,
    CONSTRAINT PK_MS_VIA PRIMARY KEY (ID),
    CONSTRAINT FK_MS_VIA_MS_CRUZAMENTO_CRUZAMENTO_ID FOREIGN KEY (CRUZAMENTO_ID)
        REFERENCES MS_CRUZAMENTO (ID) ON DELETE CASCADE
);
CREATE INDEX IX_MS_VIA_CRUZAMENTO_ID ON MS_VIA (CRUZAMENTO_ID);

CREATE TABLE MS_SENSOR (
    ID                 RAW(16)         NOT NULL,
    CODIGO             NVARCHAR2(20)   NOT NULL,
    CRUZAMENTO_ID      RAW(16)         NOT NULL,
    VIA_ID             RAW(16)         NOT NULL,
    TIPO               NVARCHAR2(30)   NOT NULL,   -- LacoIndutivo | Camera
    SEGREDO_HASH       NVARCHAR2(200)  NOT NULL,
    ATIVO              NUMBER(1)       NOT NULL,
    CRIADO_EM          TIMESTAMP(7)    NOT NULL,
    ULTIMA_LEITURA_EM  TIMESTAMP(7),
    CONSTRAINT PK_MS_SENSOR PRIMARY KEY (ID),
    CONSTRAINT FK_MS_SENSOR_MS_CRUZAMENTO_CRUZAMENTO_ID FOREIGN KEY (CRUZAMENTO_ID)
        REFERENCES MS_CRUZAMENTO (ID) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IX_MS_SENSOR_CODIGO ON MS_SENSOR (CODIGO);
CREATE UNIQUE INDEX IX_MS_SENSOR_VIA_ID ON MS_SENSOR (VIA_ID);  -- um sensor por via
CREATE INDEX IX_MS_SENSOR_CRUZAMENTO_ID ON MS_SENSOR (CRUZAMENTO_ID);

CREATE TABLE MS_LEITURA_SENSOR (
    ID                    RAW(16)        NOT NULL,
    SENSOR_ID             RAW(16)        NOT NULL,
    VIA_ID                RAW(16)        NOT NULL,
    CRUZAMENTO_ID         RAW(16)        NOT NULL,
    LEITURA_EXTERNA_ID    NVARCHAR2(64)  NOT NULL,
    COLETADA_EM           TIMESTAMP(7)   NOT NULL,
    RECEBIDA_EM           TIMESTAMP(7)   NOT NULL,
    VEICULOS_CONTADOS     NUMBER(10)     NOT NULL,
    TAMANHO_FILA          NUMBER(10)     NOT NULL,
    VELOCIDADE_MEDIA_KMH  BINARY_DOUBLE,
    CONSTRAINT PK_MS_LEITURA_SENSOR PRIMARY KEY (ID),
    CONSTRAINT FK_MS_LEITURA_SENSOR_MS_SENSOR_SENSOR_ID FOREIGN KEY (SENSOR_ID)
        REFERENCES MS_SENSOR (ID) ON DELETE CASCADE
);
-- Chave natural de idempotência da telemetria: a mesma leitura nunca entra duas vezes.
CREATE UNIQUE INDEX IX_MS_LEITURA_SENSOR_SENSOR_ID_LEITURA_EXTERNA_ID ON MS_LEITURA_SENSOR (SENSOR_ID, LEITURA_EXTERNA_ID);
CREATE INDEX IX_MS_LEITURA_SENSOR_CRUZAMENTO_ID_COLETADA_EM ON MS_LEITURA_SENSOR (CRUZAMENTO_ID, COLETADA_EM);
CREATE INDEX IX_MS_LEITURA_SENSOR_VIA_ID_COLETADA_EM ON MS_LEITURA_SENSOR (VIA_ID, COLETADA_EM);

CREATE TABLE MS_PLANO_SEMAFORICO (
    ID                                 RAW(16)          NOT NULL,
    CRUZAMENTO_ID                      RAW(16)          NOT NULL,
    MODO                               NVARCHAR2(30)    NOT NULL,   -- Adaptativo | TempoFixo | Contingencia | Emergencia
    CICLO_SEGUNDOS                     NUMBER(10)       NOT NULL,
    TEMPO_TRAVESSIA_PEDESTRE_SEGUNDOS  NUMBER(10)       NOT NULL,
    TRAVESSIA_ACESSIVEL                NUMBER(1)        NOT NULL,
    JUSTIFICATIVA                      NVARCHAR2(2000)  NOT NULL,
    GERADO_EM                          TIMESTAMP(7)     NOT NULL,
    VERIFICADO_EM                      TIMESTAMP(7)     NOT NULL,
    ENCERRADO_EM                       TIMESTAMP(7),
    VIGENTE                            NUMBER(1)        NOT NULL,
    CONSTRAINT PK_MS_PLANO_SEMAFORICO PRIMARY KEY (ID),
    CONSTRAINT FK_MS_PLANO_SEMAFORICO_MS_CRUZAMENTO_CRUZAMENTO_ID FOREIGN KEY (CRUZAMENTO_ID)
        REFERENCES MS_CRUZAMENTO (ID) ON DELETE CASCADE
);
CREATE INDEX IX_MS_PLANO_SEMAFORICO_CRUZAMENTO_ID_VIGENTE ON MS_PLANO_SEMAFORICO (CRUZAMENTO_ID, VIGENTE);

CREATE TABLE MS_FASE_PLANO (
    ID                       RAW(16)         NOT NULL,
    PLANO_ID                 RAW(16)         NOT NULL,
    ORDEM                    NUMBER(10)      NOT NULL,
    VIA_ID                   RAW(16)         NOT NULL,
    NOME_VIA                 NVARCHAR2(100)  NOT NULL,
    VERDE_SEGUNDOS           NUMBER(10)      NOT NULL,
    AMARELO_SEGUNDOS         NUMBER(10)      NOT NULL,
    VERMELHO_GERAL_SEGUNDOS  NUMBER(10)      NOT NULL,
    FLUXO_VEICULOS_HORA      BINARY_DOUBLE   NOT NULL,
    TAXA_OCUPACAO            BINARY_DOUBLE   NOT NULL,
    CONSTRAINT PK_MS_FASE_PLANO PRIMARY KEY (ID),
    CONSTRAINT FK_MS_FASE_PLANO_MS_PLANO_SEMAFORICO_PLANO_ID FOREIGN KEY (PLANO_ID)
        REFERENCES MS_PLANO_SEMAFORICO (ID) ON DELETE CASCADE
);
CREATE INDEX IX_MS_FASE_PLANO_PLANO_ID ON MS_FASE_PLANO (PLANO_ID);

CREATE TABLE MS_OCORRENCIA (
    ID               RAW(16)         NOT NULL,
    CRUZAMENTO_ID    RAW(16)         NOT NULL,
    AUTOR_ID         RAW(16)         NOT NULL,
    TIPO             NVARCHAR2(30)   NOT NULL,
    DESCRICAO        NVARCHAR2(500)  NOT NULL,
    PRIORIDADE       NVARCHAR2(30)   NOT NULL,   -- Baixa | Media | Alta | Critica
    STATUS           NVARCHAR2(30)   NOT NULL,   -- Aberta | EmAnalise | Resolvida | Rejeitada
    RESPOSTA_GESTOR  NVARCHAR2(500),
    CRIADA_EM        TIMESTAMP(7)    NOT NULL,
    ATUALIZADA_EM    TIMESTAMP(7)    NOT NULL,
    CONSTRAINT PK_MS_OCORRENCIA PRIMARY KEY (ID),
    -- Sem ON DELETE: o histórico do cidadão impede excluir cruzamento/usuário.
    CONSTRAINT FK_MS_OCORRENCIA_MS_CRUZAMENTO_CRUZAMENTO_ID FOREIGN KEY (CRUZAMENTO_ID) REFERENCES MS_CRUZAMENTO (ID),
    CONSTRAINT FK_MS_OCORRENCIA_MS_USUARIO_AUTOR_ID FOREIGN KEY (AUTOR_ID) REFERENCES MS_USUARIO (ID)
);
CREATE INDEX IX_MS_OCORRENCIA_AUTOR_ID ON MS_OCORRENCIA (AUTOR_ID);
CREATE INDEX IX_MS_OCORRENCIA_CRUZAMENTO_ID ON MS_OCORRENCIA (CRUZAMENTO_ID);
CREATE INDEX IX_MS_OCORRENCIA_STATUS_PRIORIDADE ON MS_OCORRENCIA (STATUS, PRIORIDADE);

CREATE TABLE MS_SOLICITACAO_TRAVESSIA (
    ID             RAW(16)        NOT NULL,
    CRUZAMENTO_ID  RAW(16)        NOT NULL,
    USUARIO_ID     RAW(16)        NOT NULL,
    MOTIVO         NVARCHAR2(30)  NOT NULL,
    SOLICITADA_EM  TIMESTAMP(7)   NOT NULL,
    EXPIRA_EM      TIMESTAMP(7)   NOT NULL,
    CONSTRAINT PK_MS_SOLICITACAO_TRAVESSIA PRIMARY KEY (ID),
    CONSTRAINT FK_MS_SOLICITACAO_TRAVESSIA_MS_CRUZAMENTO_CRUZAMENTO_ID FOREIGN KEY (CRUZAMENTO_ID)
        REFERENCES MS_CRUZAMENTO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_MS_SOLICITACAO_TRAVESSIA_MS_USUARIO_USUARIO_ID FOREIGN KEY (USUARIO_ID) REFERENCES MS_USUARIO (ID)
);
CREATE INDEX IX_MS_SOLICITACAO_TRAVESSIA_CRUZAMENTO_ID_EXPIRA_EM ON MS_SOLICITACAO_TRAVESSIA (CRUZAMENTO_ID, EXPIRA_EM);
CREATE INDEX IX_MS_SOLICITACAO_TRAVESSIA_USUARIO_ID ON MS_SOLICITACAO_TRAVESSIA (USUARIO_ID);

CREATE TABLE MS_ACIONAMENTO_EMERGENCIA (
    ID              RAW(16)        NOT NULL,
    CRUZAMENTO_ID   RAW(16)        NOT NULL,
    VIA_ID          RAW(16)        NOT NULL,
    SOLICITANTE_ID  RAW(16)        NOT NULL,
    TIPO_VEICULO    NVARCHAR2(30)  NOT NULL,   -- Ambulancia | Bombeiros | Policia | DefesaCivil
    ACIONADO_EM     TIMESTAMP(7)   NOT NULL,
    EXPIRA_EM       TIMESTAMP(7)   NOT NULL,
    ENCERRADO_EM    TIMESTAMP(7),
    CONSTRAINT PK_MS_ACIONAMENTO_EMERGENCIA PRIMARY KEY (ID),
    CONSTRAINT FK_MS_ACIONAMENTO_EMERGENCIA_MS_CRUZAMENTO_CRUZAMENTO_ID FOREIGN KEY (CRUZAMENTO_ID)
        REFERENCES MS_CRUZAMENTO (ID) ON DELETE CASCADE
);
CREATE INDEX IX_MS_ACIONAMENTO_EMERGENCIA_CRUZAMENTO_ID_EXPIRA_EM ON MS_ACIONAMENTO_EMERGENCIA (CRUZAMENTO_ID, EXPIRA_EM);

CREATE TABLE MS_IDEMPOTENCIA (
    ID               RAW(16)         NOT NULL,
    ESCOPO           NVARCHAR2(300)  NOT NULL,
    CHAVE            NVARCHAR2(100)  NOT NULL,
    HASH_REQUISICAO  NVARCHAR2(64)   NOT NULL,
    CONCLUIDO        NUMBER(1)       NOT NULL,
    STATUS_CODE      NUMBER(10)      NOT NULL,
    CONTENT_TYPE     NVARCHAR2(100),
    LOCATION         NVARCHAR2(500),
    CORPO_RESPOSTA   NCLOB,
    CRIADO_EM        TIMESTAMP(7)    NOT NULL,
    EXPIRA_EM        TIMESTAMP(7)    NOT NULL,
    CONSTRAINT PK_MS_IDEMPOTENCIA PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX IX_MS_IDEMPOTENCIA_ESCOPO_CHAVE ON MS_IDEMPOTENCIA (ESCOPO, CHAVE);
CREATE INDEX IX_MS_IDEMPOTENCIA_EXPIRA_EM ON MS_IDEMPOTENCIA (EXPIRA_EM);

