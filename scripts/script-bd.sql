-- A API cria estas tabelas sozinha na 1ª inicialização (BancoDados:CriarTabelasAutomaticamente=true).
-- Este script existe para: (1) entrega da disciplina de DevOps (/scripts/script-bd.sql),
-- (2) criar o schema manualmente se preferirem, (3) documentar o modelo.
-- Tipos equivalentes ao mapeamento do EF Core (Oracle.EntityFrameworkCore, compatibilidade 19):
--   Guid → RAW(16) | string(n) → NVARCHAR2(n) | int → NUMBER(10) | double → BINARY_DOUBLE
--   bool → NUMBER(1) | DateTime (UTC) → TIMESTAMP(7) | enum → NVARCHAR2(30) (texto legível)
-- Prefixo MS_ = MoveSync (não colide com tabelas de outras disciplinas no mesmo usuário).
-- =============================================================================

